static const char* TAG = "main";

struct EngineIpcCtx {
    InferenceEngine* engine;
    ModelConfig      cfg;
    esp_err_t        result;
};

static void ipc_engine_deinit(void* arg) {
    auto* ctx = static_cast<EngineIpcCtx*>(arg);
    if (!ctx || !ctx->engine) return;
    ctx->engine->deinit();
    ctx->result = ESP_OK;
}

static void ipc_engine_init(void* arg) {
    auto* ctx = static_cast<EngineIpcCtx*>(arg);
    if (!ctx || !ctx->engine) {
        if (ctx) ctx->result = ESP_ERR_INVALID_ARG;
        return;
    }
    ctx->result = ctx->engine->init(&ctx->cfg);
}

static esp_err_t engine_switch_via_ipc(InferenceEngine* engine,
                                       const ModelConfig& next_cfg,
                                       const ModelConfig& rollback_cfg)
{
    if (!engine) return ESP_ERR_INVALID_ARG;

    const int this_core = xPortGetCoreID();
    const int ipc_core  = (this_core == 0) ? 1 : 0;

    EngineIpcCtx deinit_ctx{ .engine = engine, .cfg = {}, .result = ESP_OK };
    esp_err_t ret = esp_ipc_call_blocking(ipc_core, ipc_engine_deinit, &deinit_ctx);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "IPC deinit falló: %s", esp_err_to_name(ret));
        return ret;
    }

    EngineIpcCtx init_ctx{ .engine = engine, .cfg = next_cfg, .result = ESP_FAIL };
    ret = esp_ipc_call_blocking(ipc_core, ipc_engine_init, &init_ctx);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "IPC init falló: %s", esp_err_to_name(ret));
        return ret;
    }

    if (init_ctx.result != ESP_OK) {
        EngineIpcCtx rollback_ctx{ .engine = engine, .cfg = rollback_cfg, .result = ESP_FAIL };
        esp_err_t rollback_ipc = esp_ipc_call_blocking(ipc_core, ipc_engine_init, &rollback_ctx);
        if (rollback_ipc != ESP_OK) {
            ESP_LOGE(TAG, "IPC rollback falló: %s", esp_err_to_name(rollback_ipc));
        } else if (rollback_ctx.result != ESP_OK) {
            ESP_LOGE(TAG, "Rollback init falló: %s", esp_err_to_name(rollback_ctx.result));
        }
    }

    return init_ctx.result;
}

// ─── Crop buffer (224×224 RGB565) para JPEG stream ────────────────────────
// Allocated once in PSRAM.  224 × 224 × 2 = 100 352 bytes
static uint8_t* s_crop_rgb565 = nullptr;

/// Extract center 224×224 crop from 320×240 RGB565 frame into s_crop_rgb565.
static void crop_224(const camera_fb_t* fb) {
    const uint16_t* src = reinterpret_cast<const uint16_t*>(fb->buf);
    uint16_t*       dst = reinterpret_cast<uint16_t*>(s_crop_rgb565);
    for (int y = 0; y < INPUT_HEIGHT; ++y) {
        const uint16_t* row = &src[(y + CROP_OFFSET_Y) * CAMERA_WIDTH + CROP_OFFSET_X];
        std::memcpy(&dst[y * INPUT_WIDTH], row, INPUT_WIDTH * sizeof(uint16_t));
    }
}

